// Host-PIN: Rechte per API prüfen (ohne Browser). Aufruf: node test/pin.js
const fs = require('fs'), path = require('path'), os = require('os'), { spawn } = require('child_process');
const ROOT = path.join(__dirname, '..'), PORT = 3470, B = 'http://localhost:' + PORT;
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), 'qa-pin-'));
const OHNE = new Set(['.git', 'einstellungen.json', 'verlauf.json', 'hue.json', '_repo', 'test', 'spotify.json', 'https.json', '.https', 'host.json']);
fs.cpSync(ROOT, TMP, { recursive: true, filter: s => !OHNE.has(path.basename(s)) });
let srv; const start = () => { srv = spawn(process.execPath, ['server.js'], { cwd: TMP, env: { ...process.env, PORT: String(PORT), NO_BROWSER: '1' } }); };
const post = (p, b) => fetch(B + p, { method: 'POST', body: JSON.stringify(b) }).then(async r => ({ status: r.status, ...(await r.json().catch(() => ({}))) }));
const sleep = ms => new Promise(r => setTimeout(r, ms));
let fehler = 0; const ok = (c, t) => { console.log((c ? '  ✓ ' : '  ✗ ') + t); if (!c) fehler++; };
const views = {};
const sse = (id, role) => fetch(B + '/events?' + (role ? 'role=tv' : 'id=' + id)).then(async r => { const rd = r.body.getReader(), dec = new TextDecoder(); let buf = '';
  for (;;) { const { value, done } = await rd.read(); if (done) break; buf += dec.decode(value); let k; while ((k = buf.indexOf('\n\n')) >= 0) { const l = buf.slice(0, k).split('\n').find(x => x.startsWith('data: ')); buf = buf.slice(k + 2); if (l) views[role || id] = JSON.parse(l.slice(6)); } } }).catch(() => {});
(async () => {
  start(); await sleep(1300);
  const A = (await post('/api/join', { name: 'Anna', avatar: '🦊' })).id; sse(A);
  await sleep(100);
  const Bn = (await post('/api/join', { name: 'Ben', avatar: '🐼' })).id; sse(Bn); sse(null, 'tv');
  await sleep(500);
  console.log('Ohne PIN');
  ok(views[A].me.isVip && views[A].me.canTech && views[A].me.canLead, 'Anna (zuerst da) ist 👑 und darf alles');
  ok((await post('/api/hue', { id: Bn, action: 'status' })).status === 403, 'Ben darf nicht an Hue');
  ok((await post('/api/pin', { id: Bn, action: 'set', pin: '1111' })).ok === false, 'Ben darf keine PIN festlegen');
  const s1 = await post('/api/pin', { id: A, action: 'set', pin: '1234' });
  ok(s1.ok && s1.token, 'Anna legt PIN 1234 fest und bekommt ein Handy-Token');
  await sleep(300);
  ok(views[A].pin.set && views[A].me.authed, 'PIN gesetzt, Anna angemeldet');
  console.log('Mit PIN');
  ok((await post('/api/pin', { id: Bn, action: 'login', pin: '0000' })).ok === false, 'Ben mit falscher PIN abgelehnt');
  ok((await post('/api/pin', { id: Bn, action: 'login', pin: '1234' })).ok, 'Ben mit richtiger PIN angemeldet');
  await sleep(300);
  ok(views[Bn].me.isVip, 'Krone geht an Ben');
  ok(views[A].me.canTech && !views[A].me.canLead, 'Anna: angemeldet → Technik ja, Spiel leiten nein (Krone weg)');
  ok((await post('/api/advance', { id: A })).status === 403, 'Anna kann das Spiel nicht starten');
  const C = (await post('/api/join', { name: 'Cleo', avatar: '🐸' })).id; sse(C); await sleep(300);
  ok((await post('/api/pin', { id: Bn, action: 'crown', target: C })).ok, 'Ben übergibt die Krone an Cleo (nicht angemeldet)');
  await sleep(300);
  ok(views[C].me.isVip && views[C].me.canLead && !views[C].me.canTech, 'Cleo leitet das Spiel, kommt aber nicht an die Technik');
  ok((await post('/api/system', { id: C, action: 'reboot' })).status === 403, 'Cleo darf den Pi nicht neu starten');
  ok((await post('/api/einstellungen', { id: C, settings: views[C].packs ? {} : {} })).status !== 403, 'Cleo darf Spiel-Einstellungen ändern');
  ok((await post('/api/pin', { id: Bn, action: 'options', protectGame: true })).ok, 'Ben schützt auch „Spiel leiten“');
  await sleep(300);
  ok(!views[C].me.canLead, 'Cleo darf jetzt nicht mehr leiten');
  ok((await post('/api/pin', { id: C, action: 'crown', target: A })).ok === false, 'Cleo kann die Krone nicht weitergeben');
  ok((await post('/api/pin', { id: Bn, action: 'options', protectGame: false })).ok, '„Spiel leiten“ wieder frei');
  console.log('Gemerktes Handy nach Neustart');
  srv.kill(); await sleep(600); start(); await sleep(1300);
  const A2 = (await post('/api/join', { name: 'Anna', avatar: '🦊' })).id; sse(A2);
  const D = (await post('/api/join', { name: 'Dirk', avatar: '🦁' })).id; sse(D); await sleep(400);
  ok(!views[A2].me.authed, 'nach Neustart erst nicht angemeldet');
  ok((await post('/api/pin', { id: A2, action: 'token', token: s1.token })).ok, 'Token vom gemerkten Handy wird angenommen');
  await sleep(300);
  ok(views[A2].me.authed && views[A2].me.isVip, 'Anna wieder Host mit Krone');
  ok((await post('/api/pin', { id: D, action: 'token', token: 'falsch' })).ok === false, 'falsches Token abgelehnt');
  console.log('PIN vergessen: Code am Fernseher');
  sse(null, 'tv'); await sleep(300);
  ok((await post('/api/pin', { id: D, action: 'resetstart' })).ok, 'Dirk fordert einen Code an');
  await sleep(300);
  const code = views.tv.pinReset && views.tv.pinReset.code;
  ok(/^\d{4}$/.test(code || ''), `Fernseher zeigt Code ${code}`);
  ok(!views[D].pinReset && !JSON.stringify(views[D]).includes('"code"'), 'Handys bekommen den Code nicht');
  ok((await post('/api/pin', { id: D, action: 'resetcode', code: code === '0000' ? '1111' : '0000', pin: '9999' })).ok === false, 'falscher Code abgelehnt');
  const r = await post('/api/pin', { id: D, action: 'resetcode', code, pin: '9999' });
  ok(r.ok, 'richtiger Code + neue PIN 9999');
  await sleep(300);
  ok(views[D].me.isVip && views[D].me.authed && !views[A2].me.authed, 'Dirk ist Host, Anna abgemeldet');
  ok((await post('/api/pin', { id: A2, action: 'token', token: s1.token })).ok === false, 'altes gemerktes Handy gilt nicht mehr');
  console.log('Durchprobieren');
  let last; for (let i = 0; i < 6; i++) last = await post('/api/pin', { id: A2, action: 'login', pin: String(1000 + i) });
  ok(/Fehlversuche/.test(last.text || ''), 'nach 5 Fehlversuchen gesperrt');
  ok((await post('/api/pin', { id: A2, action: 'login', pin: '9999' })).ok === false, 'auch die richtige PIN geht während der Sperre nicht');
  console.log(fehler ? `\n${fehler} Fehler` : '\nAlles in Ordnung.');
  srv.kill(); fs.rmSync(TMP, { recursive: true, force: true }); process.exit(fehler ? 1 : 0);
})();
